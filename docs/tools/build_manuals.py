def compile_pdfs(only: list[str] | None = None) -> None:
    """Compile with xelatex into a temporary folder, then copy the PDF back.

    Build files go outside the project folder because cloud-sync clients
    (OneDrive, Dropbox) can corrupt .aux files while LaTeX is writing them.
    Two passes: the first writes the table of contents, the second prints it.
    """
    for doc in only or DOCS:
        if not (MANUAL / f"{doc}.tex").exists():
            continue
        with tempfile.TemporaryDirectory() as tmp:
            cmd = ["xelatex", "-interaction=nonstopmode", "-halt-on-error", f"-output-directory={tmp}", f"{doc}.tex"]
            for _ in range(2):
                result = subprocess.run(cmd, cwd=MANUAL, capture_output=True, text=True, encoding="utf-8", errors="replace")
                if result.returncode != 0:
                    print(result.stdout[-4000:])
                    sys.exit(f"LaTeX failed for {doc}")
            shutil.copy(Path(tmp) / f"{doc}.pdf", MANUAL / f"{doc}.pdf")
        print(f"built docs/manual/{doc}.pdf")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="only verify snippets")
    parser.add_argument("--only", nargs="*", help="build only these documents")
    args = parser.parse_args()
    extract()
    print(f"{results_macros()} result numbers read from benchmark_summary.json")
    if not args.check:
        compile_pdfs(args.only)


if __name__ == "__main__":
    main()
