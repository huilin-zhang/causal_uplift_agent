r"""Build the four manuals (operation manual and code guide, English and Chinese).

    python docs/tools/build_manuals.py            # extract snippets + compile PDFs
    python docs/tools/build_manuals.py --check    # only verify every snippet still exists

How the code guide stays in sync with the code: the .tex files never paste
code. They write \snippet{app/causal/metrics.py:true_qini}. This script finds
that function or class with Python's ast module, reads its current first and
last line, and writes generated/snippets.tex, which tells LaTeX to print
exactly those lines from the real source file. If a referenced name no
longer exists, the build stops with an error.
"""

from __future__ import annotations

import argparse
import ast
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MANUAL = ROOT / "docs" / "manual"
GENERATED = MANUAL / "generated"
SNIPPET = re.compile(r"\\snippet\{([^}:]+):([^}]+)\}")
DOCS = ["operation_manual_en", "operation_manual_zh", "code_guide_en", "code_guide_zh"]
BS = "\\"  # one backslash, to keep the LaTeX strings below readable


def find_span(path: Path, qualname: str) -> tuple[int, int]:
    """First and last line of a top-level function/class, Class.method, or a module constant."""
    tree = ast.parse(path.read_text(encoding="utf-8"))
    nodes, target = tree.body, None
    for part in qualname.split("."):
        defs = [n for n in nodes if isinstance(n, (ast.FunctionDef, ast.ClassDef, ast.AsyncFunctionDef)) and n.name == part]
        consts = [n for n in nodes if isinstance(n, ast.Assign) and any(getattr(t, "id", None) == part for t in n.targets)]
        target = (defs + consts or [None])[0]
        if target is None:
            raise KeyError(f"{qualname} not found in {path.relative_to(ROOT).as_posix()}")
        nodes = getattr(target, "body", [])
    start = min([target.lineno] + [d.lineno for d in getattr(target, "decorator_list", [])])
    return start, target.end_lineno


def snippet_definition(rel: str, qualname: str, first: int, last: int) -> str:
    title = f"{BS}texttt{{{rel.replace('_', BS + '_')}}}, lines {first}--{last}"
    listing = (
        f"{BS}lstinputlisting[firstline={first},lastline={last},firstnumber={first},"
        f"title={{{title}}}]{{../../{rel}}}"
    )
    return f"{BS}expandafter{BS}def{BS}csname snip@{rel}:{qualname}{BS}endcsname{{{listing}}}\n"


def extract() -> int:
    """Write generated/snippets.tex with one definition per snippet used in the manuals."""
    GENERATED.mkdir(parents=True, exist_ok=True)
    refs = set()
    for doc in DOCS:
        tex = MANUAL / f"{doc}.tex"
        if tex.exists():
            refs |= set(SNIPPET.findall(tex.read_text(encoding="utf-8")))
    errors, lines = [], ["% Generated by docs/tools/build_manuals.py. Do not edit.\n"]
    for rel, qualname in sorted(refs):
        try:
            first, last = find_span(ROOT / rel, qualname)
        except (KeyError, FileNotFoundError) as exc:
            errors.append(str(exc))
            continue
        lines.append(snippet_definition(rel, qualname, first, last))
    if errors:
        print("Missing code referenced by the manuals:\n  " + "\n  ".join(errors))
        sys.exit(1)
    (GENERATED / "snippets.tex").write_text("".join(lines), encoding="utf-8")
    print(f"{len(refs)} snippets extracted")
    return len(refs)


MODELS = {"churn_risk": "Risk", "kmeans": "Kmeans", "constant_ate": "Const", "t_learner": "Tl",
          "x_learner": "Xl", "causal_forest": "Cf", "ipw": "Ipw", "oracle": "Oracle", "random": "Random"}


def _f(x, digits: int = 2, sign: bool = False) -> str:
    """Number for LaTeX math-free text: thousands separators, real minus sign."""
    if x is None:
        return "--"
    s = f"{x:+,.{digits}f}" if sign else f"{x:,.{digits}f}"
    return s.replace("-", "$-$").replace(",", "{,}")


